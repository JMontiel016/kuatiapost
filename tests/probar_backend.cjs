/* Pruebas ejecutables sin envío a SIFEN. Requieren Node 22+ y TypeScript instalado
 * en el proyecto (npm install). node tests/probar_backend.cjs */
const assert=require('node:assert/strict');
const fs=require('node:fs');const os=require('node:os');const path=require('node:path');
const ts=require('typescript');
const base=path.resolve(__dirname,'..');
const temp=fs.mkdtempSync(path.join(os.tmpdir(),'kuatiapost-test-'));
const input=fs.readFileSync(path.join(base,'lib/usuario/almacen.ts'),'utf8');
const compiled=ts.transpileModule(input,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
fs.writeFileSync(path.join(temp,'almacen.cjs'),compiled);
process.env.KUATIAPOST_DATA_DIR=path.join(temp,'db');
const m=require(path.join(temp,'almacen.cjs'));
const usuario1=m.registrar('a@example.com','ClaveEjemplo#1234');
const usuario2=m.registrar('b@example.com','ClaveEjemplo#5678');
assert.notEqual(usuario1.id,usuario2.id);
assert.equal(m.autenticar('a@example.com','ClaveIncorrecta'),null);
assert.equal(m.autenticar('a@example.com','ClaveEjemplo#1234').id,usuario1.id);
const sesion=m.nuevaSesion(usuario1);
assert.equal(m.obtenerUsuario(sesion.token).id,usuario1.id);
assert.equal(m.obtenerUsuario('inexistente'),null);
m.guardarEspacio(usuario1.id,{body:'{"demo":"privado"}',token:'NO_GUARDAR',password:'NO_GUARDAR',connections:[{id:'x',name:'Producción',url:'https://ejemplo.com',token:'NO_GUARDAR'}]});
assert.equal(m.leerEspacio(usuario2.id).body,undefined);
assert.equal(m.leerEspacio(usuario1.id).body,'{"demo":"privado"}');
assert.equal(m.leerEspacio(usuario1.id).token,undefined);
assert.equal(m.leerEspacio(usuario1.id).connections[0].token,undefined);
const cdc='01234567890123456789012345678901234567890123';
const lineas=[{cdc,indice:0,cantidad:'3',total:'8'}];
const id1='11111111-1111-4111-8111-111111111111';
const id2='22222222-2222-4222-8222-222222222222';
m.reservarRemision(usuario1.id,id1,lineas);
assert.throws(()=>m.reservarRemision(usuario1.id,id1,lineas),/ya fue procesado/);
assert.throws(()=>m.reservarRemision(usuario1.id,id2,[{cdc,indice:0,cantidad:'6',total:'8'}]),/insuficiente/);
const respuesta=m.resolverRemision(usuario1.id,id1,{http:200,data:{Estado:'Aprobado',CDC:'7'.repeat(44)}});
assert.equal(respuesta.estado,'aprobado');
assert.throws(()=>m.resolverRemision(usuario1.id,id1,{http:200,data:{Estado:'Aprobado'}}),/ya se procesó/);
m.reservarRemision(usuario1.id,id2,[{cdc,indice:0,cantidad:'5',total:'8'}]);
assert.equal(m.resolverRemision(usuario1.id,id2,{http:200,data:{Estado:'Pendiente'}}).estado,'incierto');
assert.throws(()=>m.reservarRemision(usuario1.id,'33333333-3333-4333-8333-333333333333',[{cdc,indice:0,cantidad:'1',total:'8'}]),/insuficiente/);
assert.equal(m.listarRemisiones(usuario2.id).length,0);
m.cerrarSesion(sesion.token);
assert.equal(m.obtenerUsuario(sesion.token),null);
fs.rmSync(temp,{recursive:true,force:true});
console.log('OK: cuentas aisladas, credenciales excluidas, sesiones, SQLite y reservas atómicas.');
